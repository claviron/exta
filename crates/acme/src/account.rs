use std::path::PathBuf;

use serde::{Deserialize, Serialize};

pub const ACCOUNTS_PATH: &str = "accounts";
pub const ACCOUNT_FILE_NAME: &str = "private_key.json";
pub const ACCOUNT_KEY_FILE_NAME: &str = "private.key";

pub const CSR_FILE_NAME: &str = "request.csr";
pub const CERT_TEXT_PATH: &str = "certificate.txt";
pub const CERT_META_PATH: &str = "meta.json";

use claviron::ssl::Algorithm;

use crate::AcmeMode;
use crate::cryptex::jwk::AcmeJwk;

/// One ACME account — the long-lived identity that issues certs.
///
/// An account is created once via [`crate::actions::account::new_account`]
/// (file-based) or seeded into the `hosting.accounts` table (DB-based)
/// and reused for every subsequent cert order. The account key is the
/// JWS signing key for **all** ACME requests this account makes;
/// regenerating it requires a new account registration with the CA.
///
/// File layout (per mode):
///
/// ```text
/// <base_dir>/accounts/<staging|production>/<account_name>/
///     ├─ private.key         (PEM, ECDSA P-256 by default)
///     └─ private_key.json    (this struct, serialized; key field is
///                              skipped on disk and re-read from
///                              `private.key` on `from_file`)
/// ```
///
/// `key` (PEM) is held in memory only — `#[serde(skip)]` keeps the
/// JSON metadata file away from the private material. [`Account::load`]
/// re-hydrates all deployment paths from [`AcmeConfig::base_dir`]. Deployment
/// paths are never trusted from JSON or inferred from persisted metadata.
///
/// In DB mode the same logical fields live in the `hosting.accounts`
/// table; the renewal/issuance code reads from there instead of
/// `from_file`. See [`crate::actions::database`] for the DB path.
#[derive(Debug, Serialize, Deserialize)]
pub struct Account {
    #[serde(skip)]
    key: String,
    /// Local identifier name
    pub name: String,
    /// Account URL this account belongs to
    pub url: String,
    /// Where the account private key (PEM) is stored. Runtime-only: derived
    /// from the configured ACME base directory so moving the store cannot leave
    /// a stale path embedded in metadata.
    #[serde(skip)]
    pub key_path: PathBuf,
    /// Where certificates generated by this account are stored. Runtime-only
    /// and derived from the configured ACME base directory.
    #[serde(skip)]
    pub certs_dir: PathBuf,
    /// Suggested JWS alg for this account key (e.g., "ES256" or "RS256")
    pub alg: Algorithm,
    /// Contact URIs, e.g., ["mailto:you@example.com"]
    pub contact: String,
    /// Whether ToS was agreed during registration
    pub tos_agreed: bool,
    /// ACME account mode (staging or production)
    pub mode: AcmeMode,
    // Jwk for this account
    pub jwk: AcmeJwk,
}

use crate::AcmeConfig;

impl Account {
    pub fn load(
        config: &AcmeConfig,
        mode: &AcmeMode,
        account_name: &str,
    ) -> crate::Result<Self> {
        use std::io::BufReader;
        let account_dir = config.account_dir(account_name, mode);
        let path = account_dir.join(ACCOUNT_FILE_NAME);
        let file = std::fs::File::open(&path).map_err(|_| {
            format!("unable to open account file {}", path.to_string_lossy())
        })?;

        let reader = BufReader::new(file);
        let mut cfg: Account = serde_json::from_reader(reader)
            .map_err(|e| format!("unable to read account json: {}", e))?;

        cfg.key_path = account_dir.join(ACCOUNT_KEY_FILE_NAME);
        cfg.certs_dir = config
            .base_dir()
            .join(claviron::ssl::certstore::SERVER_CERTS_DIRNAME);

        // One-shot read; blocking std I/O is fine here
        let key_pem = std::fs::read_to_string(&cfg.key_path).map_err(|e| {
            format!(
                "unable to read key from file {}: {}",
                cfg.key_path.as_path().to_string_lossy(),
                e
            )
        })?;
        cfg.jwk.validate_key(&key_pem, cfg.alg)?;
        cfg.key = key_pem;
        Ok(cfg)
    }

    pub fn with_config(
        cfg: &AcmeConfig,
        mode: &AcmeMode,
        name: &str,
    ) -> Self {
        use claviron::ssl::certstore::SERVER_CERTS_DIRNAME;

        use crate::account::ACCOUNT_KEY_FILE_NAME;
        let certs_dir = cfg.base_dir().join(SERVER_CERTS_DIRNAME);
        let key_path = cfg.account_dir(name, mode).join(ACCOUNT_KEY_FILE_NAME);
        let base_url = cfg.base_url(mode);
        let alg = cfg.alg;
        Self {
            name: name.to_string(),
            url: base_url.to_string(),
            key_path,
            certs_dir,
            alg,
            contact: cfg.organization().email.clone(),
            mode: *mode,
            tos_agreed: false,
            jwk: AcmeJwk::default(),
            key: String::new(),
        }
    }

    pub fn private_key(&self) -> &str {
        &self.key
    }

    pub fn jwk(&self) -> &AcmeJwk {
        &self.jwk
    }

    pub fn mode(&self) -> AcmeMode {
        self.mode
    }

    pub fn cert_dir(
        &self,
        cname: &str,
    ) -> PathBuf {
        self.certs_dir.join(cname)
    }
}

#[cfg(test)]
mod tests {
    use std::fs;

    use tempfile::tempdir;

    use super::{ACCOUNT_FILE_NAME, ACCOUNT_KEY_FILE_NAME, Account};
    use crate::AcmeMode;

    #[test]
    fn account_paths_follow_configured_base_dir_instead_of_serialized_metadata()
    {
        let root = tempdir().unwrap();
        let configured_root = root.path().join("configured-acme");
        let account_dir = configured_root.join("accounts/production/claviron");
        fs::create_dir_all(&account_dir).unwrap();
        let (key, jwk) = crate::cryptex::keys::generate_acme_key_with_jwk(
            &claviron::ssl::Algorithm::ES256,
        )
        .unwrap();
        fs::write(account_dir.join(ACCOUNT_KEY_FILE_NAME), &key).unwrap();

        let config: crate::AcmeConfig = serde_yaml::from_str(&format!(
            r#"
base_dir: {}
account: claviron
challenges_dir: {}/challenges
production_url: https://acme.example/directory
staging_url: https://acme-staging.example/directory
organization:
  name: Claviron
  unit: Trust
  email: certs@example.test
pre-validation: false
renew_before: 30
alg: ES256
"#,
            configured_root.display(),
            configured_root.display()
        ))
        .unwrap();

        let account = Account {
            key: String::new(),
            name: "claviron".to_string(),
            url: "https://acme.example/directory".to_string(),
            key_path: "etc/acme/accounts/production/claviron/private.key"
                .into(),
            certs_dir: "etc/acme/servers".into(),
            alg: claviron::ssl::Algorithm::ES256,
            contact: "certs@example.test".to_string(),
            tos_agreed: true,
            mode: AcmeMode::Production,
            jwk,
        };
        let mut metadata = serde_json::to_value(account).unwrap();
        let object = metadata.as_object_mut().unwrap();
        object.insert(
            "key_path".to_string(),
            serde_json::json!("etc/acme/private.key"),
        );
        object.insert(
            "certs_dir".to_string(),
            serde_json::json!("etc/acme/servers"),
        );
        let account_path = account_dir.join(ACCOUNT_FILE_NAME);
        fs::write(&account_path, serde_json::to_vec(&metadata).unwrap())
            .unwrap();

        let loaded =
            Account::load(&config, &AcmeMode::Production, "claviron").unwrap();

        assert_eq!(loaded.private_key(), key);
        assert_eq!(loaded.key_path, account_dir.join(ACCOUNT_KEY_FILE_NAME));
        assert_eq!(loaded.certs_dir, configured_root.join("servers"));
    }
}
